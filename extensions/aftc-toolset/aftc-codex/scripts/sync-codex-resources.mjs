#!/usr/bin/env node
/**
 * sync-codex-resources.mjs — regenerate the aftc-codex resource list.
 *
 * Standalone Node ESM script (Node is fundamental to pi; Python is not
 * guaranteed). Two callers:
 *   1. The extension spawns it (child_process, node exe, no shell) as the first
 *      step of every resource-touching command.
 *   2. The model runs it via bash after manual resource edits (the injected
 *      codex rules embed the absolute `node <scriptPath>` command, resolved at
 *      runtime from getPackageRoot()).
 *
 * Behaviour:
 *   - Resolve the data dir cross-platform with logic IDENTICAL to paths.ts:
 *     AFTC_TOOLSET_DATA_ROOT override -> win32 %APPDATA%\pi-aftc-toolset\data ->
 *     darwin ~/Library/Application Support/pi-aftc-toolset/data -> linux
 *     $XDG_DATA_HOME or ~/.local/share (then + "/data").
 *   - Scan <dataDir>/aftc-codex/resources/ recursively (category folders may
 *     nest topics one level deep, eg ui-ux/web/web-app.md) plus the top-level
 *     guidance files.
 *   - Write <dataDir>/aftc-codex/resources/codex-resource-list.md: a categorised
 *     list of relative paths (forward slashes) + a one-line description (each
 *     file's first heading).
 *   - BYTE-STABLE (cache-critical — the list rides the system-prompt prefix):
 *     deterministic sort, no timestamps/"generated at", and the write is SKIPPED
 *     entirely when the content is unchanged. Atomic write (tmp + rename).
 *   - Never throws: exit 0 with a note on any error, so a command's sync-first
 *     step can never break pi.
 *
 * Output format (codex-resource-list.md):
 *   <!-- AUTO-GENERATED by sync-codex-resources.mjs — do not edit by hand -->
 *   # Codex Resource List
 *   ## guidance
 *   - thought-and-action-guidance.md — Thought & Action Guidance
 *   ## languages
 *   - languages/typescript.md — TypeScript ...
 */

import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import process from "node:process";

const PACKAGE_NAME = "pi-aftc-toolset";
const LIST_FILENAME = "codex-resource-list.md";
// codex-rules.md is always injected into the system prompt (always-on), so it is
// never "discovered" via the list; the output file obviously is not listed either.
const TOP_LEVEL_EXCLUDE = new Set([LIST_FILENAME, "codex-rules.md"]);
// Known category folders are listed first in this fixed order; ANY additional
// folder discovered on disk (eg a community-created category) is appended
// after, sorted — so output stays byte-stable while no folder is ever silently
// ignored. Nested topics (depth 2, eg ui-ux/web/) list as path-form lines under
// their TOP-LEVEL category header (no sub-group headers — spec D16).
const KNOWN_CATEGORY_ORDER = [
    "languages", "libraries", "frameworks", "engines", "runtimes",
    "tools", "servers-and-containers", "database", "os", "ui-ux",
];

/** All category folders: known order first, then any extra dirs (sorted). */
function listCategoryFolders(resourcesDir) {
    let extras = [];
    try {
        extras = fs.readdirSync(resourcesDir, { withFileTypes: true })
            .filter((e) => e.isDirectory())
            .map((e) => e.name)
            .filter((name) => !KNOWN_CATEGORY_ORDER.includes(name))
            .sort(byCodeUnit);
    } catch {
        // fall through — known order only
    }
    return [...KNOWN_CATEGORY_ORDER, ...extras];
}

// --- data-dir resolution (mirror paths.ts EXACTLY) --------------------------

function getPersistentRoot() {
    const override = process.env.AFTC_TOOLSET_DATA_ROOT;
    if (override && override.trim()) return path.resolve(override);

    const home = os.homedir();
    if (process.platform === "win32") {
        const appData = process.env.APPDATA || path.join(home, "AppData", "Roaming");
        return path.join(appData, PACKAGE_NAME);
    }
    if (process.platform === "darwin") {
        return path.join(home, "Library", "Application Support", PACKAGE_NAME);
    }
    const dataHome = process.env.XDG_DATA_HOME || path.join(home, ".local", "share");
    return path.join(dataHome, PACKAGE_NAME);
}

function getDataDir() {
    return path.join(getPersistentRoot(), "data");
}

// --- helpers -----------------------------------------------------------------

/** Deterministic code-unit sort (locale-independent -> byte-stable output). */
function byCodeUnit(a, b) {
    return a < b ? -1 : a > b ? 1 : 0;
}

/** First markdown heading text in a file (fallback: basename without ".md"). */
function describeFile(absPath) {
    try {
        const text = fs.readFileSync(absPath, "utf8");
        for (const line of text.split(/\r?\n/)) {
            const m = /^#{1,6}\s+(.+?)\s*$/.exec(line);
            if (m) return m[1].trim();
        }
    } catch {
        // fall through to basename fallback
    }
    return path.basename(absPath, ".md");
}

/** Sorted *.md file names in a dir; [] if the dir is missing/unreadable. */
function listMarkdown(dir) {
    try {
        return fs.readdirSync(dir)
            .filter((name) => name.toLowerCase().endsWith(".md"))
            .filter((name) => {
                try { return fs.statSync(path.join(dir, name)).isFile(); } catch { return false; }
            })
            .sort(byCodeUnit);
    } catch {
        return [];
    }
}

/** All *.md files under a dir, RECURSIVE (nested topics, depth 2), as
 *  forward-slash paths relative to `base`, code-unit sorted. */
function listMarkdownRecursive(dir, base) {
    const out = [];
    let entries;
    try {
        entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
        return out;
    }
    for (const e of entries) {
        const p = path.join(dir, e.name);
        try {
            if (e.isDirectory()) out.push(...listMarkdownRecursive(p, base));
            else if (e.isFile() && e.name.toLowerCase().endsWith(".md")) {
                out.push(path.relative(base, p).replace(/\\/g, "/"));
            }
        } catch {
            // skip unreadable entries
        }
    }
    return out.sort(byCodeUnit);
}

/** Build the resource-list markdown (deterministic / byte-stable). */
function buildList(codexRoot, resourcesDir) {
    const lines = [];
    lines.push("<!-- AUTO-GENERATED by sync-codex-resources.mjs — do not edit by hand -->");
    lines.push("# Codex Resource List");

    let count = 0;

    // Top-level guidance files live at the codex ROOT (not in resources/).
    const topFiles = listMarkdown(codexRoot).filter((n) => !TOP_LEVEL_EXCLUDE.has(n));
    if (topFiles.length > 0) {
        lines.push("");
        lines.push("## guidance");
        for (const name of topFiles) {
            lines.push(`- ${name} — ${describeFile(path.join(codexRoot, name))}`);
            count++;
        }
    }

    // Loose *.md files directly in resources/ (the generated list itself is
    // excluded so it never appears inside its own output).
    const looseFiles = listMarkdown(resourcesDir).filter((n) => n !== LIST_FILENAME);
    if (looseFiles.length > 0) {
        lines.push("");
        lines.push("## resources");
        for (const name of looseFiles) {
            lines.push(`- ${name} — ${describeFile(path.join(resourcesDir, name))}`);
            count++;
        }
    }

    // Category folders (known order first, then any other dirs found on disk;
    // empty categories are omitted). Nested topics appear as path-form lines
    // under their top-level category header (D16).
    for (const cat of listCategoryFolders(resourcesDir)) {
        const files = listMarkdownRecursive(path.join(resourcesDir, cat), resourcesDir);
        if (files.length === 0) continue;
        lines.push("");
        lines.push(`## ${cat}`);
        for (const rel of files) {
            lines.push(`- ${rel} — ${describeFile(path.join(resourcesDir, rel))}`);
            count++;
        }
    }

    lines.push(""); // single trailing newline
    return { content: lines.join("\n"), count };
}

// --- main --------------------------------------------------------------------

function main() {
    const codexRoot = path.join(getDataDir(), "aftc-codex");
    const resourcesDir = path.join(codexRoot, "resources");
    const outFile = path.join(resourcesDir, LIST_FILENAME);

    if (!fs.existsSync(codexRoot)) {
        console.log(`[aftc-toolset] codex sync: codex root not found (${codexRoot}) — nothing to do. Enable/seed the codex first.`);
        return;
    }

    const { content, count } = buildList(codexRoot, resourcesDir);

    // Skip the write entirely when unchanged (byte-stable; no prefix churn).
    try {
        if (fs.existsSync(outFile) && fs.readFileSync(outFile, "utf8") === content) {
            console.log(`[aftc-toolset] codex sync: no changes (${count} resources).`);
            return;
        }
    } catch {
        // fall through and (re)write
    }

    // Atomic write: temp file in the same dir, then rename over the target.
    fs.mkdirSync(resourcesDir, { recursive: true });
    const tmpFile = path.join(resourcesDir, `.${LIST_FILENAME}.tmp`);
    fs.writeFileSync(tmpFile, content, "utf8");
    fs.renameSync(tmpFile, outFile);

    console.log(`[aftc-toolset] codex sync: wrote ${LIST_FILENAME} (${count} resources).`);
}

try {
    main();
} catch (err) {
    // Never throw — a command's sync-first step must not break pi.
    console.log(`[aftc-toolset] codex sync: error: ${err && err.message ? err.message : String(err)}`);
}
